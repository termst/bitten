// Bitten build (T6, v14.10): concatenates src/*.js in name order into bitten.js, moves files marked `@chunk <name>` into
// chunks/<name>.js (loaded on first use, see src/01-chunks.js) and minifies both with esbuild.
// Usage: node build.mjs              build (needs `npm install` once: esbuild, espree, eslint-scope are dev dependencies)
//        node build.mjs --check      build, then node --check every output and report the sizes
//        node build.mjs --no-minify  readable output for debugging (do not commit it: CI builds minified)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';

const root = path.dirname(new URL(import.meta.url).pathname);
const require = createRequire(import.meta.url);
const srcDir = path.join(root, 'src');
const VERSION = '14.10';
const MINIFY = !process.argv.includes('--no-minify');
const CORE_LIMIT = 2 * 1024 * 1024;

// a folder src/NN-name/ is one entry in the order, its own NN-*.js files in name order (big files split by section)
const files = fs.readdirSync(srcDir).filter((f) => /^\d\d-/.test(f)).sort().flatMap((f) => {
  const p = path.join(srcDir, f);
  if (fs.statSync(p).isDirectory()) return fs.readdirSync(p).filter((g) => /^\d\d-.*\.js$/.test(g)).sort().map((g) => f + '/' + g);
  return /\.js$/.test(f) ? [f] : [];
});

// run state, not code: a chunk setting G.mode is play, not a wrapper
const STATE_OBJ = new Set(['G', 'window', 'document', 'Math', 'console', 'localStorage', 'navigator', 'location']);
/* ---- chunks: what each chunk file writes outside itself, so CHUNKS14.place can keep its spot in every wrapper chain */
function writesOf(src, file) {
  const espree = require('espree'), eslintScope = require('eslint-scope');
  const ast = espree.parse(src, { ecmaVersion: 'latest', sourceType: 'script', range: true });
  const sm = eslintScope.analyze(ast, { ecmaVersion: 2022, sourceType: 'script' });
  const through = new Set(sm.globalScope.through.map((r) => r.identifier));
  const names = new Set(), hooks = new Set();
  let topDecl = false;
  for (const st of ast.body) if (/Declaration$/.test(st.type)) topDecl = true;
  (function walk(n) {
    if (!n || typeof n.type !== 'string') return;
    if (n.type === 'AssignmentExpression') {
      const L = n.left;
      if (L.type === 'Identifier' && through.has(L)) names.add(L.name);
      if (L.type === 'MemberExpression' && !L.computed && L.object.type === 'Identifier' && through.has(L.object) && !STATE_OBJ.has(L.object.name)) names.add(L.object.name + '.' + L.property.name);
    }
    if (n.type === 'CallExpression' && n.callee.type === 'MemberExpression' && n.callee.object.name === 'Hooks' && n.callee.property.name === 'layer') {
      const a = n.arguments[0];
      if (a && a.type === 'Literal') hooks.add(a.value); else throw new Error(`${file}: Hooks.layer with a name that is not a plain string`);
    }
    for (const k in n) { const v = n[k]; if (Array.isArray(v)) v.forEach(walk); else if (v && typeof v === 'object' && v.type) walk(v); }
  })(ast);
  return { names: [...names].sort(), hooks: [...hooks], topDecl };
}
const placeLine = (id, w) => `CHUNKS14.place(${JSON.stringify(id)}, [${w.names.map((n) => `[${JSON.stringify(n)}, () => ${n}, (v) => { ${n} = v; }]`).join(', ')}], ${JSON.stringify(w.hooks)});\n`;

let core = `/* Bitten v${VERSION}. Built by build.mjs from src/ (${files.length} files). Do not edit this file, edit src/. */\n`;
const chunks = {};     // name -> source
const chunkIds = {};
for (const f of files) {
  let s = fs.readFileSync(path.join(srcDir, f), 'utf8');
  if (!s.endsWith('\n')) s += '\n';
  const m = /@chunk ([a-z0-9-]+)/.exec(s.split('\n').slice(0, 3).join('\n'));
  if (!m) { core += s; continue; }
  const name = m[1], w = writesOf(s, f);
  core += placeLine(f, w);
  (chunkIds[name] = chunkIds[name] || []).push(f);
  // a chunk file made of IIFEs gets try/finally, so a throw can not leave the inner functions in place
  chunks[name] = (chunks[name] || `'use strict';\n/* Bitten v${VERSION} chunk ${name}. Built by build.mjs from src/. */\n`) +
    (w.topDecl ? `CHUNKS14.begin(${JSON.stringify(f)});\n${s}CHUNKS14.end(${JSON.stringify(f)});\n` : `CHUNKS14.begin(${JSON.stringify(f)}); try {\n${s}} finally { CHUNKS14.end(${JSON.stringify(f)}); }\n`);
}
const chunkUrl = (n) => `chunks/${n}.js`;
core += `CHUNKS14.coreDone(${JSON.stringify(Object.fromEntries(Object.keys(chunks).map((n) => [n, chunkUrl(n)])))}, ${JSON.stringify(chunkIds)});\n`;

/* ---- minify */
let esb = null;
if (MINIFY) {
  try { esb = require('esbuild'); } catch (e) { console.error('build.mjs: esbuild is missing. Run `npm install` once (dev dependencies), or build with --no-minify for local debugging.'); process.exit(1); }
}
const out = (code, name) => {
  if (!esb) return code;
  const head = /^\/\*[^\n]*\*\/\n/.exec(code);
  const r = esb.transformSync(code, { minify: true, charset: 'utf8', legalComments: 'none', sourcefile: name });
  return (head && name === 'bitten.js' ? head[0] : '') + r.code;
};
const coreOut = out(core, 'bitten.js');
fs.writeFileSync(path.join(root, 'bitten.js'), coreOut);
console.log(`bitten.js: ${files.length} files, ${(core.length / 1024).toFixed(0)} KB source, ${(coreOut.length / 1024).toFixed(0)} KB${esb ? ' minified' : ''}`);
fs.mkdirSync(path.join(root, 'chunks'), { recursive: true });
const keep = new Set();
for (const [n, s] of Object.entries(chunks)) {
  const o = out(s, n + '.js');
  fs.writeFileSync(path.join(root, chunkUrl(n)), o); keep.add(n + '.js');
  console.log(`${chunkUrl(n)}: ${chunkIds[n].length} files, ${(o.length / 1024).toFixed(0)} KB`);
}
for (const f of fs.readdirSync(path.join(root, 'chunks'))) if (!keep.has(f)) fs.unlinkSync(path.join(root, 'chunks', f));

// stamp sw.js with a hash of the game files: every build that changes the game installs a fresh offline copy
{
  const chunkFiles = [...keep].sort().map((f) => 'chunks/' + f);
  const h = createHash('sha256');
  for (const f of ['index.html', 'bitten.js', 'net.js', 'manifest.webmanifest', 'vendor/peerjs.min.js', ...chunkFiles]) h.update(fs.readFileSync(path.join(root, f)));
  const id = h.digest('hex').slice(0, 10), swp = path.join(root, 'sw.js'), sw = fs.readFileSync(swp, 'utf8');
  let next = sw.replace(/const BUILD = '[^']*';/, `const BUILD = '${id}';`);
  next = next.replace(/const CHUNK_FILES = \[[^\]]*\];/, `const CHUNK_FILES = ${JSON.stringify(chunkFiles)};`);
  if (!/const BUILD = '/.test(sw) || !/const CHUNK_FILES = \[/.test(sw)) throw new Error('sw.js: BUILD or CHUNK_FILES line not found');
  if (next !== sw) fs.writeFileSync(swp, next);
  console.log(`sw.js: build ${id}`);
}
if (process.argv.includes('--check')) {
  for (const f of ['bitten.js', 'net.js', 'sw.js', ...[...keep].map((c) => 'chunks/' + c)]) {
    const p = path.join(root, f);
    if (!fs.existsSync(p)) continue;
    execFileSync(process.execPath, ['--check', p], { stdio: 'inherit' });
    console.log(`node --check ${f}: ok`);
  }
  if (esb && coreOut.length > CORE_LIMIT) { console.error(`bitten.js is ${(coreOut.length / 1048576).toFixed(2)} MB, over the 2 MB core budget: move a feature into a chunk (@chunk).`); process.exitCode = 1; }
}
